// Builds my-igcse.html: the whole site in ONE self-contained file that works
// when double-clicked (file://), with no server and no internet.
//
//   npm run build
//
// Browsers refuse to load JS modules from file://, so the modules are bundled
// into a single classic script and the CSS and favicon are inlined.

import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const read = (p) => readFile(resolve(root, p), 'utf8');

const { outputFiles } = await build({
  entryPoints: [resolve(root, 'js/main.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  write: false,
  charset: 'utf8',
  legalComments: 'none',
  // Lower newer syntax (?. ?? catch{} etc.) so older phones and tablets work too.
  target: ['es2017', 'safari12'],
});

// Make sure nothing inside the inlined code can close the tag early.
const js = outputFiles[0].text.replace(/<\/(script)/gi, '<\\/$1');
const css = (await read('css/style.css')).replace(/<\/(style)/gi, '<\\/$1');
const favicon = `data:image/svg+xml,${encodeURIComponent((await read('favicon.svg')).trim())}`;
const { version } = JSON.parse(await read('package.json'));

let html = await read('index.html');
const replace = (from, to) => {
  if (!html.includes(from)) throw new Error(`index.html changed — could not find: ${from}`);
  html = html.replace(from, () => to);
};

replace('<link rel="icon" href="favicon.svg" type="image/svg+xml">', `<link rel="icon" href="${favicon}" type="image/svg+xml">`);
replace('<link rel="manifest" href="manifest.webmanifest">\n', '');
replace('<link rel="stylesheet" href="css/style.css">', `<style>${css}</style>`);
replace('<script type="module" src="js/main.js"></script>\n', '');
html = html.replace(/\s*<script nomodule>[\s\S]*?<\/script>/, '');
replace('</body>', `<script>${js}</script>\n</body>`);
html = html.replace('<!doctype html>', `<!doctype html>\n<!-- My IGCSE v${version} — single-file offline build. Generated by scripts/build-single.js; edit the source files, not this one. -->`);

await writeFile(resolve(root, 'my-igcse.html'), html);
console.log(`Built my-igcse.html (${(Buffer.byteLength(html) / 1024).toFixed(0)} KB)`);
